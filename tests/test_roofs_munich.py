# --- snapshot generator -------------------------------------------------------------------------------------------

def fold(mb_id):
    return mb_id.split("#")[0]


def snapshot(full_osm, out_path):
    """Write the 67 tagged non-flat buildings generated from ``full_osm`` (a full Overpass response)."""
    area = Area(*AREA_ARGS)
    plan = flat_plan(full_osm)
    cls = classify(load_osm_file(full_osm), area)
    tagged = {f.id: f.tags.get("roof:shape") for f in cls.buildings}
    ids = sorted({fold(o.mb_id) for o in plan.objects if tagged.get(fold(o.mb_id)) not in (None, "flat")})
    root = ET.parse(full_osm).getroot()
    ways = {w.get("id"): w for w in root.findall("way")}
    rels = {r.get("id"): r for r in root.findall("relation")}
    nodes = {n.get("id"): n for n in root.findall("node")}
    want_ways, want_rels = [], []
    for i in ids:
        kind, num = i.split(":")[1].split("/")
        (want_ways if kind == "way" else want_rels).append(num)
    member_ways = set(want_ways)
    for r in want_rels:
        member_ways.update(m.get("ref") for m in rels[r].findall("member") if m.get("type") == "way")
    node_ids = set()
    for w in member_ways:
        node_ids.update(nd.get("ref") for nd in ways[w].findall("nd"))
    base = root.find("meta").get("osm_base") if root.find("meta") is not None else "unknown"
    out = ['<?xml version="1.0" encoding="UTF-8"?>',
           '<osm version="0.6" generator="map-builder tests/test_roofs_munich.py">',
           "<note>The data included in this document is from www.openstreetmap.org. The data is made available "
           "under ODbL. Excerpt: the %d tagged non-flat buildings of the Munich Altstadt area.</note>" % len(ids),
           '<meta osm_base="%s"/>' % base]

    def tag_lines(el):
        return ["    <tag k=%s v=%s/>" % (_q(t.get("k")), _q(t.get("v"))) for t in el.findall("tag")]

    for n in sorted(node_ids, key=int):
        e = nodes[n]
        out.append('  <node id="%s" lat="%.7f" lon="%.7f"/>' % (n, float(e.get("lat")), float(e.get("lon"))))
    for w in sorted(member_ways, key=int):
        out.append('  <way id="%s">' % w)
        out += ['    <nd ref="%s"/>' % nd.get("ref") for nd in ways[w].findall("nd")]
        out += tag_lines(ways[w])
        out.append("  </way>")
    for r in sorted(want_rels, key=int):
        out.append('  <relation id="%s">' % r)
        out += ['    <member type="%s" ref="%s" role="%s"/>' % (m.get("type"), m.get("ref"), m.get("role"))
                for m in rels[r].findall("member")]
        out += tag_lines(rels[r])
        out.append("  </relation>")
    out.append("</osm>")
    with open(out_path, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(out) + "\n")
    return len(ids)


def _q(s):
    from xml.sax.saxutils import quoteattr
    return quoteattr(s)


# --- eligibility for the skeleton (roof_kind) ---------------------------------------------------------------------

def _seg_intersect(a, b, c, d):
    def orient(p, q, r):
        return (q[0] - p[0]) * (r[1] - p[1]) - (q[1] - p[1]) * (r[0] - p[0])
    o1, o2, o3, o4 = orient(a, b, c), orient(a, b, d), orient(c, d, a), orient(c, d, b)
    return o1 * o2 < 0 and o3 * o4 < 0


def _point_on_segment(p, a, b, tol=1e-6):
    return rc._dist_to_segment(p, a, b) <= tol


def ring_is_simple(ring):
    """True if no two non-adjacent edges cross or touch and no vertex repeats."""
    n = len(ring)
    if len({(round(p[0], 6), round(p[1], 6)) for p in ring}) < n:
        return False
    for i in range(n):
        a, b = ring[i], ring[(i + 1) % n]
        for j in range(i + 1, n):
            if j == i or (j + 1) % n == i or (i + 1) % n == j:
                continue
            c, d = ring[j], ring[(j + 1) % n]
            if _seg_intersect(a, b, c, d) or _point_on_segment(c, a, b) or _point_on_segment(d, a, b) \
                    or _point_on_segment(a, c, d) or _point_on_segment(b, c, d):
                return False
    return True


def merge_collinear(ring, tol=COLLINEAR_TOL_M):
    pts = list(ring)
    changed = True
    while changed and len(pts) > 3:
        changed = False
        for i in range(len(pts)):
            p, a, b = pts[i], pts[i - 1], pts[(i + 1) % len(pts)]
            if rc._dist_to_segment(p, a, b) <= tol:
                del pts[i]
                changed = True
                break
    return pts


def classify_eligibility(tagged, outer, holes, built_as_tagged_ok):
    """-> (class, reason): 'already_built', 'eligible' or 'out_of_scope' (a named reason)."""
    if built_as_tagged_ok:
        return "already_built", "built as tagged by v0.3.0"
    if tagged not in ("gabled", "hipped"):
        return "out_of_scope", "other shape (%s)" % tagged
    if holes:
        return "out_of_scope", "courtyard (has holes)"
    if not ring_is_simple(outer):
        return "out_of_scope", "not a simple polygon"
    merged = merge_collinear(outer)
    if len(merged) > SKELETON_MAX_VERTICES:
        return "out_of_scope", "more than %d vertices after merging collinear ones" % SKELETON_MAX_VERTICES
    return "eligible", "gabled/hipped, simple, no holes, %d vertices" % len(merged)


# --- building the snapshot ----------------------------------------------------------------------------------------

class _Recorder:
    """Records (eave, roof_h) of every ``build_roof`` call. With ``force_tagged`` the tagged shape is resolved even
    where v0.3.0 falls back (a fallback building keeps roof_h = 0), and the roof itself is built flat, so the heights
    are the ones a successful tagged roof would be built to."""

    def __init__(self, force_tagged):
        self.force_tagged = force_tagged
        self.calls = {}

    def __enter__(self):
        self._orig = roofs.resolve_shape, roofs.build_roof
        orig_resolve, orig_build, rec = self._orig[0], self._orig[1], self

        def resolve(shape_tag, outer, holes, prov):
            shape = orig_resolve(shape_tag, outer, holes, prov)
            if rec.force_tagged and shape_tag in roofs.SUPPORTED_SHAPES:
                return shape_tag
            return shape

        def build(mesh, ring, holes, eave_z, roof_h, shape, tags, prov, **kw):
            rec.calls[tuple(sorted(tags.items()))] = (eave_z, roof_h)
            return orig_build(mesh, ring, holes, eave_z, roof_h, "flat" if rec.force_tagged else shape,
                              tags, prov, **kw)

        roofs.resolve_shape = roofs.build_roof = None
        roofs.resolve_shape, roofs.build_roof = resolve, build
        return self

    def __exit__(self, *exc):
        roofs.resolve_shape, roofs.build_roof = self._orig


def building_objects(plan, feats):
    return [o for o in plan.objects if fold(o.mb_id) in feats]


def feature_rings(path):
    area = Area(*AREA_ARGS)
    cls = classify(load_osm_file(path), area)
    return {f.id: f for f in cls.buildings}, area


def freeze(snapshot_path, out_path):
    """Build the snapshot at the checked-out code (run at v0.3.0) and write the expected outcomes."""
    feats, area = feature_rings(snapshot_path)
    forced = {}
    with _Recorder(True) as rec:
        plan = flat_plan(snapshot_path)
        for o in building_objects(plan, feats):
            f = feats[fold(o.mb_id)]
            forced[o.mb_id] = rec.calls[tuple(sorted(f.tags.items()))]
    plan2 = flat_plan(snapshot_path)
    z_off = plan2.report["z_offset_m"]
    with tempfile.TemporaryDirectory() as d:
        pkg = os.path.join(d, "p.mbmap")
        plan_to_package(plan2, pkg, "roofs", synthetic_sources())
        decoded = rc.decode_package(pkg)
    entries, eligible = {}, 0
    for o in sorted(building_objects(plan2, feats), key=lambda o: o.mb_id):
        f = feats[fold(o.mb_id)]
        tagged = f.tags["roof:shape"]
        eave_rel, h = forced[o.mb_id]
        outer = [(p[0], p[1]) for p in f.geometry.outer]
        holes = [[(p[0], p[1]) for p in h_] for h_ in f.geometry.holes]
        tris = [t for _, t in decoded[o.mb_id]["visual"]]
        ok, failed, sig = rc.built_as_tagged(tagged, decoded[o.mb_id]["visual"], outer, holes, eave_rel - z_off,
                                      eave_rel + h - z_off) if tagged in roofs.SUPPORTED_SHAPES else (False, {}, [])
        cls, reason = classify_eligibility(tagged, outer, holes, ok)
        eligible += cls == "eligible"
        entries[o.mb_id] = {"tagged": tagged, "eave_m": round(eave_rel, 4), "roof_h_m": round(h, 4),
                            "built_shape": o.provenance.get("roof_shape_built"),
                            "roof_shape_provenance": o.provenance.get("roof_shape", "tagged"),
                            "built_as_tagged": ok, "failed_checks": sorted(failed) if tagged in roofs.SUPPORTED_SHAPES else [], "class": cls, "reason": reason,
                            "ring_vertices": len(outer), "holes": len(holes)}
    meta = {"source": "frozen from v0.3.0 (eb134a1) over a flat DEM (z = 0), PlanOptions(trees=False)",
            "total": len(entries), "baseline_built_as_tagged": sum(e["built_as_tagged"] for e in entries.values()),
            "eligible": eligible, "collinear_tol_m": COLLINEAR_TOL_M,
            "skeleton_max_vertices": SKELETON_MAX_VERTICES, "z_offset_m": z_off}
    with open(out_path, "w", encoding="utf-8", newline="\n") as fh:
        json.dump({"meta": meta, "buildings": entries}, fh, indent=1, sort_keys=True)
        fh.write("\n")
    return meta

def build_snapshot_package(path, directory):
    plan = flat_plan(path)
    pkg = os.path.join(directory, "roofs.mbmap")
    plan_to_package(plan, pkg, "roofs", synthetic_sources())
    return plan, rc.decode_package(pkg)


class _Built:
    """The snapshot built once (plan + decoded package + checks) and shared by the tests that need it."""
    data = None

    @classmethod
    def get(cls):
        if cls.data is None:
            with tempfile.TemporaryDirectory() as d:
                plan, decoded = build_snapshot_package(SNAPSHOT, d)
            feats, _ = feature_rings(SNAPSHOT)
            exp = rc.load_expected(EXPECTED)
            z_off = plan.report["z_offset_m"]
            results = {}
            for o in building_objects(plan, feats):
                e = exp["buildings"][o.mb_id]
                f = feats[o.mb_id]
                outer = [(p[0], p[1]) for p in f.geometry.outer]
                holes = [[(p[0], p[1]) for p in h] for h in f.geometry.holes]
                tris = decoded[o.mb_id]["visual"]
                results[o.mb_id] = (rc.built_as_tagged(e["tagged"], tris, outer, holes, e["eave_m"] - z_off,
                                                       e["eave_m"] + e["roof_h_m"] - z_off), o)
            cls.data = (plan, decoded, exp, results)
        return cls.data


def gabled_box(w=10.0, d=6.0, eave=3.0, rise=2.0, base=-0.3):
    """A closed gabled house (ridge along x) as ``(material, triangle)`` list; -> (tris, outer ring)."""
    R, F = rc.ROOF, rc.FACADE
    a, b, c, e = (0, 0), (w, 0), (w, d), (0, d)
    r0, r1 = (0, d / 2, eave + rise), (w, d / 2, eave + rise)

    def P(p, z):
        return (p[0], p[1], z)
    tris = []
    for p, q in ((a, b), (b, c), (c, e), (e, a)):          # walls
        tris += [(F, (P(p, base), P(q, base), P(q, eave))), (F, (P(p, base), P(q, eave), P(p, eave)))]
    tris += [(R, (P(a, eave), P(b, eave), r1)), (R, (P(a, eave), r1, r0)),            # front slope
             (R, (P(c, eave), P(e, eave), r0)), (R, (P(c, eave), r0, r1)),            # back slope
             (F, (P(b, eave), P(c, eave), r1)), (F, (P(e, eave), P(a, eave), r0))]    # gable ends
    tris += [(F, (P(a, base), P(c, base), P(b, base))), (F, (P(a, base), P(e, base), P(c, base)))]  # floor
    return tris, [a, b, c, e]


def _flip(t):
    return (t[0], t[2], t[1])


def _oriented(tris, outer):
    """Make the winding outward by testing the signed volume (the helper's hand-written windings are not trusted)."""
    vol = sum(_vol(t) for _, t in tris)
    return tris if vol > 0 else [(m, _flip(t)) for m, t in tris]


def _vol(t):
    a, b, c = t
    return (a[0] * (b[1] * c[2] - b[2] * c[1]) - a[1] * (b[0] * c[2] - b[2] * c[0]) + a[2] * (b[0] * c[1] - b[1] * c[0])) / 6


class RoofCheckerTests(unittest.TestCase):
    """The checker catches each defect it names (and passes the clean mesh), independently of the roof code."""

    def setUp(self):
        tris, self.outer = gabled_box()
        self.tris = _oriented(tris, self.outer)
        self.eave, self.top = 3.0, 5.0

    def fails(self, tris, top=None, eave=None):
        return rc.check_building(tris, self.outer, [], self.eave if eave is None else eave,
                                 self.top if top is None else top)

    def test_clean_gabled_house_passes_everything(self):
        self.assertEqual(self.fails(self.tris), {})
        self.assertEqual(rc.built_as_tagged("gabled", self.tris, self.outer, [], self.eave, self.top)[0], True)
        self.assertFalse(rc.built_as_tagged("hipped", self.tris, self.outer, [], self.eave, self.top)[0])

    def test_missing_triangle_is_not_closed(self):
        roof = [i for i, (m, _) in enumerate(self.tris) if m == rc.ROOF][0]
        self.assertIn("closed", self.fails(self.tris[:roof] + self.tris[roof + 1:]))

    def test_balanced_overlap_and_gap_are_both_reported(self):
        idx = [i for i, (m, _) in enumerate(self.tris) if m == rc.ROOF]
        tris = list(self.tris)
        tris[idx[1]] = tris[idx[0]]                  # one half of a slope is covered twice, the other not at all
        fails = self.fails(tris)
        self.assertIn("no_overlap", fails)
        self.assertIn("no_gap", fails)

    def test_vertex_below_the_eave(self):
        tris = [(m, tuple((p[0], p[1], 2.9) if (m == rc.ROOF and p[2] == 3.0 and p[:2] == (0, 0)) else p
                          for p in t)) for m, t in self.tris]
        self.assertIn("above_eave", self.fails(tris))

    def test_ridge_must_be_within_one_millimetre(self):
        self.assertEqual(self.fails(self.tris, top=self.top + 0.0009), {})
        self.assertIn("ridge", self.fails(self.tris, top=self.top + 0.002))
        self.assertIn("ridge", self.fails(self.tris, top=self.top - 0.002))

    def test_tilted_gable_end(self):
        tris = [(m, tuple((p[0] + 0.5, p[1], p[2]) if (m == rc.FACADE and p[2] == 5.0 and p[0] == 0) else p
                          for p in t)) for m, t in self.tris]
        self.assertIn("normals", self.fails(tris))

    def test_warped_roof_slope_is_not_planar(self):
        tris = [(m, tuple((p[0], p[1], p[2] + 0.004) if (m == rc.ROOF and p[:2] == (10, 0) and p[2] == 3.0) else p
                          for p in t)) for m, t in self.tris]
        self.assertIn("planar", self.fails(tris))
        self.assertEqual(rc.check_planar_faces(rc.roof_slopes(self.tris)), {})
    def test_fan_triangulated_concave_face_overlaps(self):
        outer = [(0, 0), (10, 0), (10, 10), (5, 10), (5, 5), (0, 5)]          # L shape
        fan = [(rc.ROOF, ((0, 0, 3), (outer[i][0], outer[i][1], 3), (outer[i + 1][0], outer[i + 1][1], 3)))
               for i in range(1, len(outer) - 1)]
        fails = rc.check_building(fan, outer, [], 3.0, 3.0)
        self.assertTrue({"no_overlap", "inside"} & set(fails), fails)
        good = [(rc.ROOF, tuple((p[0], p[1], 3.0) for p in t)) for t in rc.footprint_triangles(outer, [])]
        fails = rc.check_building(good, outer, [], 3.0, 3.0)
        self.assertNotIn("no_overlap", fails)
        self.assertNotIn("no_gap", fails)


class MunichRoofSnapshotTests(unittest.TestCase):
    def test_snapshot_is_the_frozen_set_of_67_buildings(self):
        _, decoded, exp, results = _Built.get()
        self.assertEqual(len(exp["buildings"]), TOTAL)
        self.assertEqual(sorted(results), sorted(exp["buildings"]))
        self.assertTrue(all(decoded[i]["visual"] for i in results))
        self.assertTrue(os.path.getsize(SNAPSHOT) + os.path.getsize(EXPECTED) < 300_000)

    def test_built_as_tagged_baseline_is_3_of_67(self):
        """The D61 metric, measured from the exported geometry: closed, covered, ridge = eave + h, and the
        silhouette of the tagged shape. Raising it is what S3-SKELETON is for."""
        _, _, exp, results = _Built.get()
        counted = sorted(i for i, (r, _) in results.items() if r[0])
        self.assertEqual(len(counted), BASELINE, counted)
        self.assertEqual(counted, sorted(i for i, e in exp["buildings"].items() if e["built_as_tagged"]))
        self.assertEqual(exp["meta"]["baseline_built_as_tagged"], BASELINE)

    def test_counted_implies_built_with_the_tagged_shape(self):
        """Counted => built as tagged. The converse fails only for the frozen non-planar gabled quads."""
        _, _, exp, results = _Built.get()
        for i, ((counted, fails, sig), o) in results.items():
            e = exp["buildings"][i]
            built = o.provenance["roof_shape_built"] == e["tagged"]
            if counted:
                self.assertTrue(built, i)
            self.assertEqual(sorted(fails), e["failed_checks"], i)
            if built and not counted:
                self.assertEqual(e["failed_checks"], ["planar"], i)
    def test_frozen_heights_and_outcomes_match_v030(self):
        _, _, exp, results = _Built.get()
        for i, (_, o) in results.items():
            e = exp["buildings"][i]
            self.assertEqual(o.provenance["roof_shape_built"], e["built_shape"], i)
            self.assertEqual(o.provenance.get("roof_shape", "tagged"), e["roof_shape_provenance"], i)
            if e["built_shape"] == e["tagged"]:
                self.assertAlmostEqual(o.provenance["eave_height_m"], e["eave_m"], 2, i)
                self.assertAlmostEqual(o.provenance["roof_height_m"], e["roof_h_m"], 2, i)

    def test_eligibility_table_covers_the_skeleton_scope(self):
        _, _, exp, _ = _Built.get()
        classes = {}
        for e in exp["buildings"].values():
            classes[e["class"]] = classes.get(e["class"], 0) + 1
        self.assertEqual(classes, {"already_built": BASELINE, "eligible": exp["meta"]["eligible"],
                                   "out_of_scope": TOTAL - BASELINE - exp["meta"]["eligible"]})
        self.assertGreaterEqual(BASELINE + exp["meta"]["eligible"], 40)        # D61 target stays reachable
        for e in exp["buildings"].values():
            if e["class"] == "out_of_scope":
                self.assertTrue(e["reason"])

    def test_skeleton_roofs_on_eligible_excerpts_tile_the_footprint(self):
        """S3-SKELETON AC7: core/skeleton.py on every eligible Munich footprint, through the shared checks."""
        from map_builder.core.skeleton import straight_skeleton
        feats, _ = feature_rings(SNAPSHOT)
        exp = rc.load_expected(EXPECTED)["buildings"]
        eligible = sorted(i for i, e in exp.items() if e["class"] == "eligible")
        self.assertEqual(len(eligible), rc.load_expected(EXPECTED)["meta"]["eligible"])
        for i in eligible:
            sk = straight_skeleton([(p[0], p[1]) for p in feats[fold(i)].geometry.outer])
            gap, overlap, outside, lifted = rc.skeleton_tiling(sk)
            self.assertLessEqual(max(gap, overlap, outside), 1e-9, i)
            self.assertEqual(len(sk.faces), len(sk.ring), i)
            self.assertEqual(rc.check_planar_faces(lifted), {}, i)
    def test_collision_matches_visual_geometry(self):
        _, decoded, _, results = _Built.get()
        for i in results:
            vis = sum(abs(rc.area2d([(p[0], p[1]) for p in t])) for _, t in decoded[i]["visual"])
            col = sum(abs(rc.area2d([(p[0], p[1]) for p in t])) for t in decoded[i]["collision"])
            self.assertTrue(decoded[i]["collision"], i)
            self.assertAlmostEqual(col, vis, delta=max(0.01, 1e-3 * vis), msg=i)


class RoofCounterexampleTests(unittest.TestCase):
    """Footprints a roof builder must not mishandle; main's outcome is frozen here and may only get better."""

    @classmethod
    def setUpClass(cls):
        cls.plan = flat_plan(COUNTEREXAMPLES)
        cls.objects = {o.mb_id: o for o in cls.plan.objects}

    def test_self_touching_ring_is_rejected(self):
        self.assertNotIn("osm:way/9001", self.objects)
        self.assertEqual([f["id"] for f in self.plan.report["invalid_features"]], ["osm:way/9001"])

    def test_courtyard_keeps_the_fallback(self):
        prov = self.objects["osm:relation/9004"].provenance
